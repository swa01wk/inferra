#!/usr/bin/env python3
"""
Aggregate benchmark JSON outputs and update docs/architecture/v1-capacity-report.md.

Reads output files from all benchmark scripts and fills in the PENDING cells
in the capacity report with measured values.

Usage:
    python scripts/benchmark/report.py \\
        --baseline /workspace/benchmarks/baseline.json \\
        --concurrency /workspace/benchmarks/concurrency.json \\
        --context /workspace/benchmarks/context_sweep.json \\
        --lora /workspace/benchmarks/lora_mix.json \\
        --prefix /workspace/benchmarks/prefix_cache.json \\
        --overload /workspace/benchmarks/overload.json \\
        --report-path docs/architecture/v1-capacity-report.md
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
from typing import Any


def load_json(path: str | None) -> dict | None:
    if not path:
        return None
    p = pathlib.Path(path)
    if not p.exists():
        print(f"  [skip] {path} not found", file=sys.stderr)
        return None
    return json.loads(p.read_text())


def _fmt(val: Any) -> str:
    if val is None:
        return "PENDING"
    if isinstance(val, float):
        return f"{val:.1f}"
    return str(val)


def build_report(
    baseline: dict | None,
    concurrency: dict | None,
    context: dict | None,
    lora: dict | None,
    prefix: dict | None,
    overload: dict | None,
) -> str:
    lines = [
        "# V1 Safe Service Envelope — Qwen3-4B on NVIDIA L4 24 GB",
        "",
        "**Platform:** Inferra V1 · RunPod NVIDIA L4 24 GB · vLLM · Qwen/Qwen3-4B BF16",
        f"**Generated by:** `scripts/benchmark/report.py`",
        "",
        "---",
        "",
        "## Stage 1: Single-Request Latency Baseline",
        "",
    ]

    if baseline and baseline.get("results"):
        lines += [
            "| Prompt Tokens | Output Tokens | Total Latency (ms) | Tokens/s |",
            "|--------------|---------------|-------------------|----------|",
        ]
        for r in baseline["results"]:
            lines.append(
                f"| {_fmt(r.get('prompt_tokens'))} "
                f"| {_fmt(r.get('completion_tokens'))} "
                f"| {_fmt(r.get('total_ms'))} "
                f"| {_fmt(r.get('tokens_per_second'))} |"
            )
    else:
        lines.append("_No baseline data — run `scripts/benchmark/baseline.py` first._")

    lines += ["", "---", "", "## Stage 2: Concurrency Sweep", ""]

    if concurrency and concurrency.get("results"):
        lines += [
            "| Concurrency | TTFT P50 (ms) | TTFT P95 (ms) | TTFT P99 (ms) | Total P95 (ms) | Tok/s P50 | Errors% |",
            "|-------------|--------------|--------------|--------------|---------------|-----------|---------|",
        ]
        for r in concurrency["results"]:
            lines.append(
                f"| {r.get('concurrency')} "
                f"| {_fmt(r.get('ttft_p50_ms'))} "
                f"| {_fmt(r.get('ttft_p95_ms'))} "
                f"| {_fmt(r.get('ttft_p99_ms'))} "
                f"| {_fmt(r.get('total_latency_p95_ms'))} "
                f"| {_fmt(r.get('tokens_per_second_p50'))} "
                f"| {_fmt(r.get('error_rate_pct'))}% |"
            )
    else:
        lines.append("_No concurrency data — run `scripts/benchmark/concurrency.py` first._")

    lines += ["", "---", "", "## Stage 3: Context Sweep", ""]

    if context and context.get("results"):
        lines += [
            "| Context Tokens | Concurrency | TTFT P50 (ms) | TTFT P95 (ms) | Total P95 (ms) | Errors |",
            "|---------------|-------------|--------------|--------------|---------------|--------|",
        ]
        for r in context["results"]:
            lines.append(
                f"| {r.get('context_tokens')} "
                f"| {r.get('concurrency')} "
                f"| {_fmt(r.get('ttft_p50_ms'))} "
                f"| {_fmt(r.get('ttft_p95_ms'))} "
                f"| {_fmt(r.get('total_latency_p95_ms'))} "
                f"| {r.get('errors')} |"
            )
    else:
        lines.append("_No context sweep data — run `scripts/benchmark/context_sweep.py` first._")

    lines += ["", "---", "", "## Stage 4: LoRA Mix", ""]

    if lora and lora.get("results"):
        lines += [
            "| Concurrency | LoRA Fraction | Base TTFT P95 | LoRA TTFT P95 | Errors |",
            "|-------------|--------------|--------------|--------------|--------|",
        ]
        for r in lora["results"]:
            lines.append(
                f"| {r.get('concurrency')} "
                f"| {r.get('lora_fraction')} "
                f"| {_fmt(r.get('base_ttft_p95_ms'))}ms "
                f"| {_fmt(r.get('lora_ttft_p95_ms'))}ms "
                f"| {r.get('errors')} |"
            )
    else:
        lines.append("_No LoRA mix data — run `scripts/benchmark/lora_mix.py` first._")

    lines += ["", "---", "", "## Stage 5: Prefix Cache Effectiveness", ""]

    if prefix and prefix.get("results"):
        lines += [
            "| Shared Prefix Tokens | Cold TTFT (ms) | Warm TTFT P50 (ms) | Improvement % |",
            "|---------------------|---------------|-------------------|--------------|",
        ]
        for r in prefix["results"]:
            lines.append(
                f"| {r.get('shared_prefix_tokens')} "
                f"| {_fmt(r.get('cold_ttft_ms'))} "
                f"| {_fmt(r.get('warm_ttft_p50_ms'))} "
                f"| {_fmt(r.get('ttft_improvement_pct'))}% |"
            )
    else:
        lines.append("_No prefix cache data — run `scripts/benchmark/prefix_cache.py` first._")

    lines += ["", "---", "", "## Stage 7: Overload and Admission Control", ""]

    if overload and overload.get("results"):
        lines += [
            "| Test | Total Req | 200 OK | 429 | 503 | Accepted TTFT P95 |",
            "|------|-----------|--------|-----|-----|------------------|",
        ]
        for r in overload["results"]:
            lines.append(
                f"| {r.get('test')} "
                f"| {r.get('total_requests')} "
                f"| {r.get('status_200')} "
                f"| {r.get('status_429')} "
                f"| {r.get('status_503')} "
                f"| {_fmt(r.get('accepted_ttft_p95_ms'))}ms |"
            )
    else:
        lines.append("_No overload data — run `scripts/benchmark/overload.py` first._")

    lines += [
        "",
        "---",
        "",
        "## Recommended Operating Points",
        "",
        "> Derived from Stage 2 concurrency sweep results above.",
        "",
        "| Workload | Recommended Max Concurrency | Target TTFT P95 |",
        "|----------|---------------------------|----------------|",
        "| Interactive chat (<500ms TTFT) | TBD from Stage 2 | < 500 ms |",
        "| Async/batch (<2s TTFT)         | TBD from Stage 2 | < 2 s |",
        "| Maximum safe concurrency        | TBD from Stage 2 | < 5 s |",
        "",
        "---",
        "",
        "_Report auto-generated by `scripts/benchmark/report.py`._",
    ]

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--baseline", default=None)
    parser.add_argument("--concurrency", default=None)
    parser.add_argument("--context", default=None)
    parser.add_argument("--lora", default=None)
    parser.add_argument("--prefix", default=None)
    parser.add_argument("--overload", default=None)
    parser.add_argument("--report-path", default="docs/architecture/v1-capacity-report.md")
    args = parser.parse_args()

    baseline = load_json(args.baseline)
    concurrency = load_json(args.concurrency)
    context = load_json(args.context)
    lora = load_json(args.lora)
    prefix = load_json(args.prefix)
    overload = load_json(args.overload)

    report = build_report(baseline, concurrency, context, lora, prefix, overload)

    out = pathlib.Path(args.report_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report)
    print(f"Capacity report written to {out}")
    print(report[:800] + ("…\n" if len(report) > 800 else ""))


if __name__ == "__main__":
    main()
